class Arduino_AXS15231B_Guition : public Arduino_AXS15231B {
public:
    Arduino_AXS15231B_Guition(Arduino_DataBus *bus, int8_t rst, uint8_t r,
                              bool ips, int16_t w, int16_t h)
        : Arduino_AXS15231B(bus, rst, r, ips, w, h) {}

protected:
    void tftInit() override {
        if (_rst != GFX_NOT_DEFINED) {
            pinMode(_rst, OUTPUT);
            digitalWrite(_rst, HIGH); delay(100);
            digitalWrite(_rst, LOW);  delay(AXS15231B_RST_DELAY);
            digitalWrite(_rst, HIGH); delay(AXS15231B_RST_DELAY);
        } else {
            _bus->sendCommand(AXS15231B_SWRESET);
            delay(AXS15231B_RST_DELAY);
        }
        _bus->batchOperation(guition_axs15231b_init, sizeof(guition_axs15231b_init));
        invertDisplay(false);
    }
};
